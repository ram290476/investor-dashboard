#!/usr/bin/env node
/**
 * Render full-desktop reference screenshots of design/ai-generated/Main.dc.html
 * for every theme in themes.json, and (re)generate the per-theme CSS token files
 * and contrast.md.
 *
 * How it works: serves design/ai-generated/ over a local HTTP server, loads
 * Main.dc.html in headless Chrome at 1440px (same as docs/design-roadmap/*.png),
 * waits for support.js to bind sample data (data-dc-preview="ready"), then
 * recolors the rendered DOM: every computed color/background/border/fill/stroke
 * literal is looked up in mockup-color-roles.json and replaced with the theme
 * token (alpha preserved). The mockup source is never modified.
 *
 * Usage (from repo root):
 *   npm i --no-save puppeteer-core     # or NODE_PATH=<dir with puppeteer-core>
 *   CHROME=/usr/bin/google-chrome node docs/design-roadmap/themes/render-themes.js [themeId ...]
 *   node docs/design-roadmap/themes/render-themes.js --no-shots   # CSS + contrast only
 */
'use strict';
const fs = require('fs');
const path = require('path');
const http = require('http');

const HERE = __dirname;
const DESIGN = path.resolve(HERE, '../../../design/ai-generated');
const themes = JSON.parse(fs.readFileSync(path.join(HERE, 'themes.json'), 'utf8'));
const roles = JSON.parse(fs.readFileSync(path.join(HERE, 'mockup-color-roles.json'), 'utf8')).roles;

// ---------- color math ----------
const hex2rgb = h => { h = h.replace('#', ''); return [0, 2, 4].map(i => parseInt(h.slice(i, i + 2), 16)); };
const rgb2hex = c => '#' + c.map(v => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')).join('').toUpperCase();
const mix = (a, b, w) => { const A = hex2rgb(a), B = hex2rgb(b); return rgb2hex(A.map((v, i) => v * w + B[i] * (1 - w))); };
const lum = h => hex2rgb(h).map(v => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); })
  .reduce((s, v, i) => s + v * [0.2126, 0.7152, 0.0722][i], 0);
const contrast = (a, b) => { const x = lum(a), y = lum(b); return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05); };

function resolveMap(t) {
  const out = {};
  for (const [src, role] of Object.entries(roles)) {
    out[src.toUpperCase()] = Array.isArray(role) ? mix(t.tokens[role[0]], t.tokens[role[1]], role[2]) : t.tokens[role];
  }
  return out;
}

// ---------- CSS + contrast ----------
function writeCss(t) {
  const lines = [`/* ${t.name} — ${t.inspiredBy} */`, `/* Generated from themes.json by render-themes.js. */`,
    `:root[data-theme="${t.id}"] {`, `  color-scheme: ${t.scheme};`];
  for (const k of themes.tokenOrder) lines.push(`  --${k}: ${t.tokens[k]};`);
  lines.push(`  --accent-subtle: ${mix(t.tokens.accent, t.tokens.surface, 0.2)};`);
  lines.push(`  --up-subtle: ${mix(t.tokens.up, t.tokens.surface, 0.15)};`);
  lines.push(`  --down-subtle: ${mix(t.tokens.down, t.tokens.surface, 0.15)};`);
  lines.push(`  --warning-subtle: ${mix(t.tokens.warning, t.tokens.surface, 0.2)};`, '}', '');
  fs.writeFileSync(path.join(HERE, `${t.id}.css`), lines.join('\n'));
}

function contrastRows(t) {
  const T = t.tokens, f = x => x.toFixed(2);
  const pairs = [
    ['text', 'bg'], ['text', 'surface'], ['text-2', 'surface'], ['text-muted', 'surface'], ['text-faint', 'surface'],
    ['accent-text', 'surface'], ['up', 'surface'], ['down', 'surface'], ['warning', 'surface'], ['up', 'bg'], ['down', 'bg']
  ];
  const rows = pairs.map(([a, b]) => { const c = contrast(T[a], T[b]); return { a, b, c, pass: c >= 7 ? 'AAA' : c >= 4.5 ? 'AA' : c >= 3 ? 'AA large / UI' : 'FAIL' }; });
  // Driver heat chips: rgba(heat, up to 0.81) over surface with --text on top.
  const heatMax = mix(T.heat, T.surface, 0.81), hc = contrast(T.text, heatMax);
  rows.push({ a: 'text', b: 'heat@81% over surface', bHex: heatMax, c: hc, pass: hc >= 7 ? 'AAA' : hc >= 4.5 ? 'AA' : hc >= 3 ? 'AA large / UI' : 'FAIL' });
  const ud = contrast(T.up, T.down);
  const series = ['series-1', 'series-2', 'series-3', 'series-4', 'series-5', 'series-6'].map(s => `${s} ${f(contrast(T[s], T.surface))}`);
  return { rows, ud, series, f };
}

function writeContrast() {
  const out = ['# Theme contrast (WCAG 2.x)', '', 'Generated by `render-themes.js` from `themes.json`. AA body text needs **4.5:1**; large text / UI graphics need **3:1**; AAA is 7:1.', ''];
  for (const t of themes.themes) {
    const { rows, ud, series, f } = contrastRows(t);
    out.push(`## ${t.name} (\`${t.id}\`)`, '', '| Foreground | Background | Ratio | Level |', '| --- | --- | --- | --- |');
    for (const r of rows) out.push(`| \`${r.a}\` ${t.tokens[r.a]} | \`${r.b}\` ${r.bHex || t.tokens[r.b]} | ${f(r.c)}:1 | ${r.pass} |`);
    out.push('', `Up vs down (luminance difference, not a text pair): ${f(ud)}:1. Chart series vs surface (non-text, target ≥ 3:1): ${series.join(' · ')}.`, '');
  }
  fs.writeFileSync(path.join(HERE, 'contrast.md'), out.join('\n'));
}

// ---------- static server ----------
function serve() {
  const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.svg': 'image/svg+xml' };
  const srv = http.createServer((req, res) => {
    const p = path.join(DESIGN, decodeURIComponent(req.url.split('?')[0]));
    if (!p.startsWith(DESIGN) || !fs.existsSync(p) || fs.statSync(p).isDirectory()) { res.writeHead(404); return res.end(); }
    res.writeHead(200, { 'Content-Type': types[path.extname(p)] || 'application/octet-stream' });
    fs.createReadStream(p).pipe(res);
  });
  return new Promise(r => srv.listen(0, '127.0.0.1', () => r(srv)));
}

// Runs in the page: recolor every element from the default palette to the theme.
function recolor(map, tokens) {
  const parse = v => { const m = v && v.match(/rgba?\(([^)]+)\)/); if (!m) return null; const p = m[1].split(/[ ,\/]+/).filter(Boolean).map(Number); return { r: p[0], g: p[1], b: p[2], a: p.length > 3 ? p[3] : 1 }; };
  const hex = c => '#' + [c.r, c.g, c.b].map(v => v.toString(16).padStart(2, '0')).join('').toUpperCase();
  const props = ['color', 'background-color', 'border-top-color', 'border-right-color', 'border-bottom-color', 'border-left-color', 'outline-color', 'fill', 'stroke', 'stop-color', 'text-decoration-color', 'caret-color'];
  const svgOnly = new Set(['fill', 'stroke', 'stop-color']);
  const unmapped = {}; const edits = [];
  for (const el of document.querySelectorAll('*')) {
    const cs = getComputedStyle(el);
    for (const pr of props) {
      if (svgOnly.has(pr) && !(el instanceof SVGElement)) continue;
      const c = parse(cs.getPropertyValue(pr));
      if (!c || c.a === 0) continue;
      const h = hex(c), to = map[h];
      if (!to) { if (h !== '#000000' && h !== '#FFFFFF') unmapped[pr + ' ' + h] = (unmapped[pr + ' ' + h] || 0) + 1; continue; }
      const n = parseInt(to.slice(1), 16);
      const val = c.a < 1 ? `rgba(${n >> 16}, ${(n >> 8) & 255}, ${n & 255}, ${c.a})` : to;
      edits.push([el, pr, val]);
    }
  }
  for (const [el, pr, val] of edits) el.style.setProperty(pr, val, 'important'); // apply after reading so inherited values are not re-mapped
  const root = document.documentElement;
  for (const [k, v] of Object.entries(tokens)) root.style.setProperty('--' + k, v);
  root.style.background = tokens.bg; document.body.style.background = tokens.bg;
  return { edits: edits.length, unmapped };
}

(async () => {
  const args = process.argv.slice(2);
  const noShots = args.includes('--no-shots');
  const only = args.filter(a => !a.startsWith('--'));
  for (const t of themes.themes) writeCss(t);
  writeContrast();
  console.log('wrote CSS token files + contrast.md');
  if (noShots) return;

  const puppeteer = require('puppeteer-core');
  const srv = await serve();
  const url = `http://127.0.0.1:${srv.address().port}/Main.dc.html`;
  const browser = await puppeteer.launch({
    executablePath: process.env.CHROME || '/usr/bin/google-chrome-stable', headless: 'new',
    args: ['--no-sandbox', '--disable-dev-shm-usage', '--font-render-hinting=none', '--hide-scrollbars']
  });
  try {
    for (const t of themes.themes) {
      if (only.length && !only.includes(t.id)) continue;
      const page = await browser.newPage();
      await page.setViewport({ width: 1440, height: 1600, deviceScaleFactor: 1 });
      await page.goto(url, { waitUntil: 'networkidle0', timeout: 90000 });
      await page.waitForFunction(() => document.documentElement.getAttribute('data-dc-preview') === 'ready');
      await page.evaluate(async () => { try { await document.fonts.ready; } catch (_) {} });
      await new Promise(r => setTimeout(r, 500));
      const holes = await page.evaluate(() => ((document.body.innerText || '').match(/\{\{/g) || []).length);
      const res = await page.evaluate(recolor, resolveMap(t), t.tokens);
      await new Promise(r => setTimeout(r, 200));
      const fullH = await page.evaluate(() => {
        // Trim the empty viewport tail below the last panel (keep 24px padding).
        let bottom = 0;
        for (const el of document.body.querySelectorAll('*')) { const r = el.getBoundingClientRect(); if (r.width && r.height && r.height < 1200 && getComputedStyle(el).position !== 'fixed') bottom = Math.max(bottom, r.bottom + window.scrollY); }
        return Math.ceil(Math.min(Math.max(document.documentElement.scrollHeight, document.body.scrollHeight), bottom + 24));
      });
      const dest = path.join(HERE, `${t.id}-desktop-full.png`);
      await page.screenshot({ path: dest, type: 'png', clip: { x: 0, y: 0, width: 1440, height: fullH } });
      console.log(`${t.id}: ${res.edits} color edits, ${holes} unbound holes, ${fs.statSync(dest).size} bytes`);
      if (Object.keys(res.unmapped).length) console.log('  unmapped:', JSON.stringify(res.unmapped));
      await page.close();
    }
  } finally { await browser.close(); srv.close(); }
})().catch(e => { console.error(e); process.exit(1); });
